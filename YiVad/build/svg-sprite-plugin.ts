/**
 * SVG icon sprite plugin — replicates vite-plugin-svg-icons behavior.
 *
 * Scans `src/assets/icons/` (recursively) for `.svg` files at build time, generates a sprite
 * (`<svg style="display:none"><symbol id="icon-NAME" viewBox="…">…</symbol>…</svg>`),
 * and exposes it via the `virtual:svg-icons-register` module alias.
 *
 * The module, when imported, injects the sprite into `document.body` for
 * runtime use by `<use xlink:href="#icon-NAME" />` in `src/components/SvgIcon/index.vue`.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { RsbuildPlugin, RsbuildPluginAPI } from "@rsbuild/core";

const MODULE_ID = "@yivad/svg-icons-register";
const ICONS_REL = "src/assets/icons";
const PREFIX = "icon";

interface IconEntry {
  id: string;
  viewBox: string;
  inner: string;
}

function walkSvgs(iconsDir: string, base = ""): IconEntry[] {
  const out: IconEntry[] = [];
  let entries: string[] = [];
  try {
    entries = readdirSync(iconsDir);
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = join(iconsDir, entry);
    let stat;
    try {
      stat = statSync(full);
    } catch {
      continue;
    }
    if (stat.isDirectory()) {
      out.push(...walkSvgs(full, base ? `${base}-${entry}` : entry));
    } else if (entry.endsWith(".svg")) {
      const name = entry.slice(0, -4);
      const id = base ? `${PREFIX}-${base}-${name}` : `${PREFIX}-${name}`;
      const raw = readFileSync(full, "utf-8");
      out.push({ id, viewBox: extractViewBox(raw), inner: extractInner(raw) });
    }
  }
  return out;
}

function extractViewBox(svg: string): string {
  const m = svg.match(/\sviewBox\s*=\s*["']([^"']+)["']/i);
  return m ? m[1] : "0 0 1024 1024";
}

function extractInner(svg: string): string {
  const start = svg.indexOf("<svg");
  const startEnd = svg.indexOf(">", start);
  const end = svg.lastIndexOf("</svg>");
  if (startEnd === -1 || end === -1) return "";
  return svg.slice(startEnd + 1, end).trim();
}

function buildSprite(icons: IconEntry[]): string {
  const symbols = icons
    .map(i => `  <symbol id="${i.id}" viewBox="${i.viewBox}">${i.inner}</symbol>`)
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n${symbols}\n</svg>`;
}

function buildModule(sprite: string): string {
  return `// generated by build/svg-sprite-plugin.ts — do not edit
  (function () {
    if (typeof document === "undefined") return;
    var container = document.createElement("div");
    container.style.display = "none";
    container.setAttribute("aria-hidden", "true");
    container.innerHTML = ${JSON.stringify(sprite)};
    var sprite = container.firstChild;
    if (sprite) document.body.insertBefore(sprite, document.body.firstChild);
  })();
  `;
}

export function svgSpritePlugin(root: string): RsbuildPlugin {
  const iconsDir = resolve(root, ICONS_REL);
  const cacheDir = resolve(root, "node_modules", ".cache", "yivad");
  const cacheFile = resolve(cacheDir, "svg-icons-register.js");

  function regenerate() {
    const icons = walkSvgs(iconsDir);
    if (!existsSync(cacheDir)) mkdirSync(cacheDir, { recursive: true });
    writeFileSync(cacheFile, buildModule(buildSprite(icons)), "utf-8");
    return icons.length;
  }

  return {
    name: "yivad-svg-sprite",
    setup(api: RsbuildPluginAPI) {
      api.modifyRsbuildConfig(config => {
        config.resolve = config.resolve ?? {};
        config.resolve.alias = { ...(config.resolve.alias ?? {}), [MODULE_ID]: cacheFile };
      });

      api.onBeforeBuild(() => {
        const n = regenerate();
        process.stdout.write(`  ℹ  svg-sprite: ${n} icon(s) registered\n`);
      });

      api.onBeforeDevCompile(() => {
        regenerate();
      });
    },
  };
}
